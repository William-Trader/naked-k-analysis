"""Deterministic price-action stance engine.

The rules encode what the 201-briefing study actually validated:
- the only robust edge was 4h bearish continuation (~66%);
- selling range lows and buying range highs lost at 24h;
- ADX < 20 has no trend edge;
- 24h directional forecasts were anti-predictive (40%).

The engine is deliberately conservative: it returns neutral unless an
edge is present. Confidence is a calibrated grade, not a probability
generated by an LLM.

2026-11-06 accuracy audit (BTC/ETH, 150d, 900 4h bars, 12bp cost):
- baseline 4h hit rate 38.6% / 42.2%, average net -0.105% / -0.078%,
  0 of 3 walk-forward folds positive on either symbol;
- the single worst bucket was high bar overlap (>=0.70): 31.6% / 25.9%
  hit, -0.236% / -0.553% average net -> hard veto below;
- entries without volume confirmation were the second loss driver;
  requiring vol_z >= 0 lifted 4h hit to 47.6% / 54.1% and average net
  to -0.033% / +0.206% (overlap < 0.70, in-sample, n=63 / 61);
- the old fixed confidence (56-64) was not monotone with outcomes:
  conf >= 62 scored 38.4% / 39.0%, below the unfiltered baseline.
  Confidence is now a quality grade from measured modifiers, capped at 60.

No positive expectancy is claimed. The gate removes known-bad trades;
it does not turn the remaining sample into a profitable system.
"""
from __future__ import annotations


def _round(x, nd=2):
    return None if x is None else round(float(x), nd)


def stance(f: dict, params: dict | None = None) -> dict:
    """Return direction/confidence/levels from a feature dict.

    params: optional override dict (see nakedk.params.DEFAULTS). Absent keys
    fall back to the historical defaults, so existing callers are unaffected.
    """
    p = params or {}
    adx_trend = p.get("stance_adx_trend", 20.0)
    pos_short = p.get("stance_pos_short", 0.30)
    pos_long = p.get("stance_pos_long", 0.70)
    stop_atr = p.get("stance_stop_atr", 1.5)
    target_atr = p.get("stance_target_atr", 3.0)
    overlap_max = p.get("stance_overlap_max", 0.70)
    min_vol_z = p.get("stance_min_vol_z", 0.0)

    price = f["price"]
    adx = f.get("adx14") or 0.0
    rsi = f.get("rsi14") or 50.0
    pos20 = f.get("pos20")
    atr = f.get("atr14")
    overlap = f.get("overlap")
    vol_z = f.get("vol_z")
    e20, e50 = f.get("ema20"), f.get("ema50")
    reasons = []

    direction = "neutral"
    confidence = 50
    evidence = []

    def _quality(adx_value, vol_z_value, overlap_value) -> int:
        """Measured quality grade, capped at 60 (see module docstring)."""
        c = 50
        if 20.0 <= adx_value < 30.0:
            c += 6
        elif adx_value >= 40.0:
            c -= 6
        if vol_z_value is not None and vol_z_value >= 0.5:
            c += 3
        if overlap_value is not None:
            if overlap_value >= 0.65:
                c -= 4
            elif overlap_value < 0.55:
                c += 2
        return max(35, min(60, c))

    if atr is None or e20 is None or e50 is None or pos20 is None:
        reasons.append("insufficient feature set")
    elif overlap is not None and overlap >= overlap_max:
        reasons.append(
            f"overlap {overlap:.2f} >= {overlap_max:g}: choppy, no tradable structure")
    elif adx < adx_trend:
        reasons.append(f"ADX {adx:.1f} < {adx_trend:g}: no trend edge")
    elif pos20 < pos_short:
        # Never short the bottom of the range.
        if price > e20 and rsi < 45:
            direction = "long"
            confidence = _quality(adx, vol_z, overlap)
            reasons.append("range-low mean reversion: price above EMA20, RSI < 45")
        else:
            reasons.append(f"pos20 {pos20:.2f} < {pos_short:g}: shorting is disabled")
    elif pos20 > pos_long:
        # Never buy the top of the range.
        if price < e20 and rsi > 55:
            direction = "short"
            confidence = _quality(adx, vol_z, overlap)
            reasons.append("range-high mean reversion: price below EMA20, RSI > 55")
        else:
            reasons.append(f"pos20 {pos20:.2f} > {pos_long:g}: buying is disabled")
    elif e20 > e50 and price > e20:
        if vol_z is not None and vol_z < min_vol_z:
            reasons.append(
                f"vol_z {vol_z:+.2f} < {min_vol_z:g}: no volume confirmation")
        else:
            direction = "long"
            confidence = _quality(adx, vol_z, overlap)
            reasons.append("EMA20 > EMA50, price above EMA20, volume confirmed")
    elif e20 < e50 and price < e20:
        if vol_z is not None and vol_z < min_vol_z:
            reasons.append(
                f"vol_z {vol_z:+.2f} < {min_vol_z:g}: no volume confirmation")
        else:
            direction = "short"
            confidence = _quality(adx, vol_z, overlap)
            reasons.append("EMA20 < EMA50, price below EMA20, volume confirmed")
    else:
        reasons.append("mixed structure: no directional edge")

    if atr:
        if direction == "long":
            stop = price - stop_atr * atr
            target = price + target_atr * atr
        elif direction == "short":
            stop = price + stop_atr * atr
            target = price - target_atr * atr
        else:
            stop = target = None
    else:
        stop = target = None

    evidence.append(f"overlap={overlap}")
    evidence.append(f"vol_z={vol_z}")
    evidence.append(f"adx={round(adx, 1)}")

    return {
        "direction": direction,
        "confidence": confidence,
        "grade": ("A" if confidence >= 56 else
                  "B" if confidence >= 50 else "C"),
        "evidence": evidence,
        "horizon_h": 4,
        "entry": _round(price),
        "stop": _round(stop),
        "target": _round(target),
        "reasons": reasons,
    }


def signal_line(symbol: str, s: dict) -> str:
    """Machine-readable line used by the scoring loop."""
    return "SIGNAL|{}|{}|{}h|{}|entry={}|stop={}|target={}".format(
        symbol.replace("USDT", ""), s["direction"], s["horizon_h"],
        s["confidence"], s.get("entry"), s.get("stop"), s.get("target"),
    )
